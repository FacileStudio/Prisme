// TestUpStampsALegacyDatabaseAfterStatus covers an operator who ran
// `migrate status` before the first boot: goose then created the ledger with
// only its version 0 sentinel, and the baseline must still be stamped rather
// than run.
func TestUpStampsALegacyDatabaseAfterStatus(t *testing.T) {
	assertStampsLegacy(t, "prisme_migrations_status",
		`CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now());
		 INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true);`)
}

func legacySchema(t *testing.T, ledger string) func(*gorm.DB) error {
	t.Helper()
	up := baselineUp(t)
	return func(db *gorm.DB) error {
		if ledger != "" {
			if err := db.Exec(ledger).Error; err != nil {
				return err
			}
		}
		if err := db.Exec(up).Error; err != nil {
			return err
		}
		return db.Exec(`INSERT INTO porte_users (email, name) VALUES ('ada@facile.studio', 'Ada');
			INSERT INTO accounts (user_id, localpart, matrix_user_id, created_at)
			SELECT id, 'ada', '@ada:prisme.test', '2026-01-02T03:04:05Z' FROM porte_users`).Error
	}
}

func assertStampsLegacy(t *testing.T, prefix, ledger string) {
	t.Helper()
	db := openSchema(t, prefix, legacySchema(t, ledger))
	if columnDefault(t, db, "accounts", "created_at") != "" {
		t.Fatal("the legacy schema already has the defaults migration")
	}
	if err := runUp(db); err != nil {
		t.Fatalf("up on a legacy database: %v", err)
	}
	wantVersions(t, db)
	if got := columnDefault(t, db, "accounts", "created_at"); got != "now()" {
		t.Fatalf("accounts.created_at default %q, want now()", got)
	}
	assertRowsKept(t, db)
}

func assertRowsKept(t *testing.T, db *gorm.DB) {
	t.Helper()
	var kept struct {
		Localpart string
		Name      string
	}
	err := db.Raw(`SELECT a.localpart, u.name FROM accounts a JOIN porte_users u ON u.id = a.user_id`).Scan(&kept).Error
	if err != nil {
		t.Fatalf("read the row: %v", err)
	}
	if kept.Localpart != "ada" || kept.Name != "Ada" {
		t.Fatalf("the existing rows changed: %+v", kept)
	}
}

// TestColumnDefaultsGoDownAndUp runs the defaults migration down and up again
// on a migrated schema, which is what a rollback and a second release do.
func TestColumnDefaultsGoDownAndUp(t *testing.T) {
	db := openSchema(t, "prisme_migrations_redo", runUp)
	sqlDB, err := db.DB()
	if err != nil {
		t.Fatalf("handle: %v", err)
	}
	provider, err := goose.NewProvider(goose.DialectPostgres, sqlDB, FS, goose.WithDisableGlobalRegistry(true))
	if err != nil {
		t.Fatalf("provider: %v", err)
	}
	ctx := context.Background()
	if _, err := provider.Down(ctx); err != nil {
		t.Fatalf("down: %v", err)
	}
	if got := columnDefault(t, db, "spaces", "created_at"); got != "" {
		t.Fatalf("spaces.created_at default %q after down, want none", got)
	}
	if got := appliedVersions(t, db); len(got) != 1 || got[0] != 1 {
		t.Fatalf("applied versions %v after down, want [1]", got)
	}
	if err := runUp(db); err != nil {
		t.Fatalf("up after down: %v", err)
	}
	if got := columnDefault(t, db, "spaces", "created_at"); got != "now()" {
		t.Fatalf("spaces.created_at default %q after up, want now()", got)
	}
}
